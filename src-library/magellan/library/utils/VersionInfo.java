package magellan.library.utils;

import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.MissingResourceException;
import java.util.PropertyResourceBundle;
import java.util.ResourceBundle;


import magellan.library.utils.logging.Logger;

/**
 * A class for retrieving and comparing versioning information about Magellan.
 * <p>
 * There is deliberately no online update check: this fork does not contact any server to look for newer versions.
 * </p>
 */
public class VersionInfo {
  private static final Logger log = Logger.getInstance(VersionInfo.class);

  /**
   * Name of the classpath resource that carries the version of this build. It is generated by the Maven build
   * (filtered from <code>src/main/resources/magellan-version.properties</code>) and is therefore only present in
   * Maven builds. Other builds (Ant, plain IDE) fall back to the <code>etc/VERSION</code> file.
   */
  public static final String VERSION_RESOURCE = "/magellan-version.properties";
  /** Key of the semantic version in {@link #VERSION_RESOURCE} and in <code>etc/VERSION</code> */
  private static final String KEY_SEMANTIC_VERSION = "SEMANTIC_VERSION";
  /** if not null, then we have already read the value */
  private static String Version = null;

  /**
   * Gets the Version of this Instance.
   * <p>
   * The version is looked up in this order:
   * </p>
   * <ol>
   * <li>the classpath resource {@link #VERSION_RESOURCE} written by the Maven build. It is part of the jar, so it is
   * always the version of the code that is actually running (also if a stale <code>etc/VERSION</code> lies around).</li>
   * <li>the file <code>etc/VERSION</code> (or <code>VERSION</code>) below the given directory, which is generated by
   * the Ant build.</li>
   * </ol>
   * 
   * @param magellanDirectory Directory to look for the version file; may be <code>null</code> if only the classpath
   *          should be used.
   * @return The semantic version, or <code>null</code> if it can't be determined.
   */
  public static String getVersion(File magellanDirectory) {
    if (VersionInfo.Version != null)
      return VersionInfo.Version;

    String version = readVersionFromClasspath();
    if (version == null) {
      version = readVersionFromFile(magellanDirectory);
    }
    // only cache success, so that a later call with a valid directory can still find the file
    VersionInfo.Version = version;
    return version;
  }

  /**
   * Reads the version from {@link #VERSION_RESOURCE}.
   * 
   * @return The version or <code>null</code> if the resource is not part of the classpath (non-Maven build).
   */
  private static String readVersionFromClasspath() {
    try (InputStream stream = VersionInfo.class.getResourceAsStream(VersionInfo.VERSION_RESOURCE)) {
      if (stream == null)
        return null;
      ResourceBundle bundle = new PropertyResourceBundle(stream);
      String version = bundle.getString(KEY_SEMANTIC_VERSION);
      // an unfiltered resource (e.g. copied by an IDE) would still contain the placeholder
      return (version.isEmpty() || version.contains("${")) ? null : version;
    } catch (IOException e) {
      // do nothing, not important
    } catch (MissingResourceException e) {
      // do nothing, not important
    }
    return null;
  }

  /**
   * Reads the version from the <code>etc/VERSION</code> file, as generated by the Ant build.
   * 
   * @return The version or <code>null</code> if the file can't be found or read.
   */
  private static String readVersionFromFile(File magellanDirectory) {
    if (magellanDirectory == null)
      return null;
    try {
      File versionFile = new File(magellanDirectory, "etc/VERSION");
      if (!versionFile.exists()) {
        // hmmm, maybe one directory level up (special Eclipse problem with bin directory)
        versionFile = new File(magellanDirectory.getParentFile(), "etc/VERSION");
        if (!versionFile.exists()) {
          // last try, eclipse special...try just Mag2 Dir
          versionFile = new File(magellanDirectory.getParentFile(), "VERSION");
          if (!versionFile.exists())
            // okay, I'll give up...
            return null;
        }
      }

      try (InputStream stream = new FileInputStream(versionFile)) {
        return new PropertyResourceBundle(stream).getString(KEY_SEMANTIC_VERSION);
      }
    } catch (IOException e) {
      // do nothing, not important
    } catch (MissingResourceException e) {
      // do nothing, not important
    }

    return null;
  }

  /**
   * Returns rue if firstVersion is strictly greater than secondVersion.
   * 
   */
  public static boolean isNewer(String firstVersion, String secondVersion) {
    if (Utils.isEmpty(secondVersion) || Utils.isEmpty(firstVersion))
      return false;

    VersionInfo.log.debug("Current: " + secondVersion);
    VersionInfo.log.debug("Newest : " + firstVersion);

    Version a = new Version(firstVersion);
    Version b = new Version(secondVersion);
    return a.isNewer(b);
  }
}
